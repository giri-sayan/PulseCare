-- 00_init_user.sql
-- Initializes the PULSECARE_DB user and privileges in XEPDB1
ALTER SESSION SET CONTAINER = XEPDB1;

BEGIN
   EXECUTE IMMEDIATE 'DROP USER PULSECARE_DB CASCADE';
EXCEPTION
   WHEN OTHERS THEN
      IF SQLCODE != -1918 THEN
         NULL;
      END IF;
END;
/

CREATE USER PULSECARE_DB IDENTIFIED BY "PulseCare#2026"
  DEFAULT TABLESPACE users
  TEMPORARY TABLESPACE temp
  QUOTA UNLIMITED ON users;

GRANT CONNECT, RESOURCE, CREATE VIEW, CREATE PROCEDURE, CREATE SEQUENCE, CREATE TRIGGER TO PULSECARE_DB;
GRANT UNLIMITED TABLESPACE TO PULSECARE_DB;

EXIT;
